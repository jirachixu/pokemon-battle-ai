"""
AlphaZero-Style Expert Iteration (ExIt) Training Script for Pokemon VGC.
Trains the MaskablePPO neural network policy and value head directly on targets
generated by the 2-turn game-theoretic Nash equilibrium lookahead search engine.
"""

from __future__ import annotations
import os
import collections
import uuid
import re
from typing import Optional
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim

from sb3_contrib import MaskablePPO
from sb3_contrib.common.maskable.distributions import MaskableCategoricalDistribution
from sb3_contrib.common.maskable.policies import MaskableMultiInputActorCriticPolicy
from stable_baselines3.common.monitor import Monitor
from poke_env.ps_client.account_configuration import AccountConfiguration
from poke_env.player import SimpleHeuristicsPlayer

from src.env import VGCEnv
from src.simulation import SimulatedBattleState
from src.search import LookaheadSearch, LookaheadPlayer
from src.models import VGCFeatureExtractor, TeamPreviewModel

# Transition structure for Expert Iteration replay buffer
Transition = collections.namedtuple(
    "Transition",
    ["observation", "action_mask", "target_policy", "target_value"]
)

class ExpertIterationTrainer:
    """
    Orchestrates the AlphaZero / Expert Iteration training loop:
    1. Collects self-play or sparring battle trajectories where moves are chosen
    by the 2-turn Nash equilibrium lookahead search.
    2. Trains the MaskablePPO actor network to predict the lookahead's search policy.
    3. Trains the MaskablePPO critic network to predict the final game outcome.
    """

    def __init__(
        self,
        model: MaskablePPO,
        training_environment: VGCEnv,
        preview_model: TeamPreviewModel,
        search_depth: int = 2,
        search_candidates_limit: int = 10,
        replay_buffer_capacity: int = 15000,
        learning_rate: float = 1e-4,
        batch_size: int = 64,
        policy_loss_weight: float = 1.0,
        value_loss_weight: float = 0.5,
        entropy_weight: float = 0.01,
        checkpoint_directory: str = "./checkpoints/expert_iteration/",
        best_model_directory: str = "./checkpoints/best_model/",
        device: str = "cuda" if (torch and torch.cuda.is_available()) else "cpu",
        eval_environment: Optional[VGCEnv] = None,
    ):
        self.model = model
        self.training_environment = training_environment
        self.eval_environment = eval_environment
        self.search_depth = search_depth
        self.searcher = LookaheadSearch(
            depth=search_depth,
            max_candidates=search_candidates_limit,
        )
        self.replay_buffer: collections.deque[Transition] = collections.deque(maxlen=replay_buffer_capacity)
        self.batch_size = batch_size
        self.policy_loss_weight = policy_loss_weight
        self.value_loss_weight = value_loss_weight
        self.entropy_weight = entropy_weight
        self.checkpoint_directory = checkpoint_directory
        self.best_model_directory = best_model_directory
        self.preview_model = preview_model
        self.device = device

        os.makedirs(self.checkpoint_directory, exist_ok=True)
        os.makedirs(self.best_model_directory, exist_ok=True)

        if torch is not None and optim is not None:
            self.optimizer = optim.Adam(self.model.policy.parameters(), lr=learning_rate)
            self.preview_optimizer = optim.Adam(self.preview_model.parameters(), lr=1e-4)
        else:
            self.optimizer = None
            self.preview_optimizer = None
        
    def collect_lookahead_episode(self) -> tuple[float, int]:
        """
        Plays a full battle where every decision is computed by the 2-turn lookahead search.
        Records the (observation, action_mask, search_policy_target) transitions.
        Returns (episode_reward, episode_turn_count).
        """
        if torch is None or self.preview_optimizer is None:
            raise RuntimeError("PyTorch is required to train the team preview model.")
        
        observation, _ = self.training_environment.reset()
        episode_transitions: list[tuple[dict[str, np.ndarray], np.ndarray, np.ndarray]] = []
        is_terminated = False
        is_truncated = False
        cumulative_reward = 0.0
        # Record the team preview decision for policy/value training
        preview_data = self.training_environment.agent.last_preview_decision
        preview_log_probability = preview_data["log_probability"]
        preview_value = preview_data["value"]

        while not (is_terminated or is_truncated):
            current_battle = self.training_environment.current_battle
            current_action_mask = self.training_environment.action_masks()

            # 1. Convert live battle state to forward simulation snapshot
            simulated_state = SimulatedBattleState.from_battle(current_battle, fill_unrevealed=True)

            # 2. Query the current neural network policy and value head to guide the search
            tensor_obs, _ = self.model.policy.obs_to_tensor(observation)
            with torch.no_grad():
                distribution = self.model.policy.get_distribution(tensor_obs, action_masks=current_action_mask)
                if not isinstance(distribution, MaskableCategoricalDistribution):
                    raise TypeError("Expected MaskableCategoricalDistribution from policy")
                categorical_distribution = distribution.distribution
                policy_probs_tensor: torch.Tensor = categorical_distribution.probs
                policy_probs = policy_probs_tensor.squeeze(0).cpu().numpy()
                state_value_pred = float(self.model.policy.predict_values(tensor_obs).squeeze().item())

            top_nn_action = int(np.argmax(policy_probs))
            top_nn_prob = float(policy_probs[top_nn_action])

            # AlphaZero root exploration noise (80% prior + 20% Dirichlet noise on legal actions)
            legal_indices = np.where(current_action_mask)[0]
            if len(legal_indices) > 1:
                dirichlet_noise = np.random.dirichlet([0.3] * len(legal_indices)).astype(np.float32)
                noisy_policy_prior = policy_probs.copy()
                noisy_policy_prior[legal_indices] = (0.80 * policy_probs[legal_indices]) + (0.20 * dirichlet_noise)
            else:
                noisy_policy_prior = policy_probs

            # 3. RUN 2-TURN GAME-THEORETIC NASH SEARCH (DIRECTLY GUIDED BY MODEL WEIGHTS)
            search_result = self.searcher.search(simulated_state, policy_prior=noisy_policy_prior)

            # 4. Construct target policy distribution from search result
            target_policy_distribution = np.zeros(676, dtype=np.float32)
            if search_result.action_distribution:
                for simulated_action_pair, probability in search_result.action_distribution.items():
                    action_code = self.searcher.to_env_action(simulated_action_pair, current_battle)
                    if 0 <= action_code < 676 and current_action_mask[action_code]:
                        target_policy_distribution[action_code] += probability

            # If distribution is single-action or empty, place full probability on best action
            chosen_action_code = int(min(675, max(0, self.searcher.to_env_action(search_result.best_action, current_battle))))
            if not current_action_mask[chosen_action_code]:
                if len(legal_indices) > 0:
                    chosen_action_code = int(legal_indices[0])

            if target_policy_distribution.sum() == 0.0:
                target_policy_distribution[chosen_action_code] = 1.0
            else:
                target_policy_distribution /= target_policy_distribution.sum()

            # Execute action: sample from Nash mixed distribution 85% of turns to prevent deterministic traps
            if np.random.rand() < 0.85 and target_policy_distribution.sum() > 0.0:
                sampled_action = int(np.random.choice(676, p=target_policy_distribution))
                if current_action_mask[sampled_action]:
                    chosen_action_code = sampled_action

            # Record transition for this turn
            episode_transitions.append((observation, current_action_mask, target_policy_distribution))

            # 5. Step environment with the lookahead-chosen action
            observation, reward, is_terminated, is_truncated, _ = self.training_environment.step(chosen_action_code)
            cumulative_reward += reward
            turn_count = len(episode_transitions)
            print(
                f"    [Turn {current_battle.turn:2d} (Step {turn_count:2d})] "
                f"Action: {chosen_action_code:3d} (NN Top: {top_nn_action:3d} p={top_nn_prob:.2f} V={state_value_pred:+.2f}) | "
                f"Step Reward: {reward:+.3f} | Total: {cumulative_reward:+.3f}"
            )

        # Determine final battle outcome value for value head target: +1.0 for win, -1.0 for loss
        final_game_outcome = 1.0 if cumulative_reward > 0.0 else (-1.0 if cumulative_reward < 0.0 else 0.0)
        # Use item() to prevent gradient tracking for the advantage calculation, otherwise when calculating value gradient 
        # it will backprop through the policy loss part as well
        advantage = final_game_outcome - preview_value.item()
        policy_loss = -preview_log_probability * advantage
        value_loss = 0.5 * ((preview_value - final_game_outcome) ** 2)
        entropy_loss = -0.01 * preview_data["entropy"]
        preview_loss = policy_loss + value_loss + entropy_loss
        
        self.preview_optimizer.zero_grad()
        preview_loss.backward()
        self.preview_optimizer.step()

        # Store transitions with final game outcome into the replay buffer
        for transition_observation, transition_mask, transition_target_policy in episode_transitions:
            self.replay_buffer.append(
                Transition(
                    observation=transition_observation,
                    action_mask=transition_mask,
                    target_policy=transition_target_policy,
                    target_value=final_game_outcome,
                )
            )

        episode_length = len(episode_transitions)
        return cumulative_reward, episode_length

    def train_step(self) -> tuple[float, float, float]:
        """
        Samples a mini-batch from the lookahead replay buffer and updates
        the MaskablePPO policy and value network weights using gradient descent.
        Returns (total_loss, policy_loss, value_loss).
        """
        if torch is None or self.optimizer is None:
            raise RuntimeError("PyTorch is required for Expert Iteration training.")

        if len(self.replay_buffer) < self.batch_size:
            return 0.0, 0.0, 0.0

        sample_indices = np.random.choice(len(self.replay_buffer), size=self.batch_size, replace=False)
        sampled_batch = [self.replay_buffer[index] for index in sample_indices]

        # Collate observations dictionary
        batch_numeric = torch.as_tensor(
            np.array([transition.observation["numeric"] for transition in sampled_batch]),
            dtype=torch.float32,
            device=self.device,
        )
        batch_abilities = torch.as_tensor(
            np.array([transition.observation["abilities"] for transition in sampled_batch]),
            dtype=torch.float32,
            device=self.device,
        )
        batch_items = torch.as_tensor(
            np.array([transition.observation["items"] for transition in sampled_batch]),
            dtype=torch.float32,
            device=self.device,
        )
        observation_tensors = {
            "numeric": batch_numeric,
            "abilities": batch_abilities,
            "items": batch_items,
        }

        action_masks_array = np.array([transition.action_mask for transition in sampled_batch])
        target_policies_tensor = torch.as_tensor(
            np.array([transition.target_policy for transition in sampled_batch]),
            dtype=torch.float32,
            device=self.device,
        )
        target_values_tensor = torch.as_tensor(
            np.array([transition.target_value for transition in sampled_batch]),
            dtype=torch.float32,
            device=self.device,
        ).unsqueeze(-1)

        # Forward pass through MaskablePPO policy
        distribution = self.model.policy.get_distribution(observation_tensors, action_masks=action_masks_array)
        if not isinstance(distribution, MaskableCategoricalDistribution):
            raise TypeError("Expected MaskableCategoricalDistribution from policy")
        categorical_distribution = distribution.distribution
        predicted_logits: torch.Tensor = categorical_distribution.logits  # Shape: (batch_size, 676)
        log_probabilities = torch.log_softmax(predicted_logits, dim=-1)

        # Cross-Entropy Policy Loss: trains the network to output the search distribution
        policy_loss = -(target_policies_tensor * log_probabilities).sum(dim=-1).mean()

        # Mean Squared Error Value Loss: trains the critic to predict the game outcome
        predicted_values = self.model.policy.predict_values(observation_tensors)  # Shape: (batch_size, 1)
        value_loss = 0.5 * torch.nn.functional.mse_loss(predicted_values, target_values_tensor)

        # Policy Entropy Regularization: prevents mode collapse onto deterministic single actions
        probabilities = torch.softmax(predicted_logits, dim=-1)
        entropy = -(probabilities * log_probabilities).sum(dim=-1).mean()

        total_loss = (
            (self.policy_loss_weight * policy_loss)
            + (self.value_loss_weight * value_loss)
            - (self.entropy_weight * entropy)
        )

        # Backpropagation
        self.optimizer.zero_grad()
        total_loss.backward()
        torch.nn.utils.clip_grad_norm_(self.model.policy.parameters(), max_norm=0.5)
        self.optimizer.step()

        return float(total_loss.item()), float(policy_loss.item()), float(value_loss.item())

    def evaluate_benchmark(self, n_episodes: int = 5) -> tuple[float, float, float]:
        """
        Evaluates current neural network policy against benchmark environment (SimpleHeuristicsPlayer)
        in pure greedy deterministic mode (0 exploration noise).
        Returns (win_rate, mean_reward, mean_turns).
        """
        if self.eval_environment is None:
            return 0.0, 0.0, 0.0

        wins = 0
        rewards: list[float] = []
        turns: list[int] = []

        for _ in range(n_episodes):
            observation, _ = self.eval_environment.reset()
            is_terminated = False
            is_truncated = False
            cumulative_reward = 0.0
            turn_count = 0

            while not (is_terminated or is_truncated):
                current_action_mask = self.eval_environment.action_masks()
                tensor_obs, _ = self.model.policy.obs_to_tensor(observation)
                with torch.no_grad():
                    distribution = self.model.policy.get_distribution(tensor_obs, action_masks=current_action_mask)
                    if isinstance(distribution, MaskableCategoricalDistribution):
                        policy_probs = distribution.distribution.probs.squeeze(0).cpu().numpy()
                    else:
                        policy_probs = np.ones(676, dtype=np.float32)

                legal_indices = np.where(current_action_mask)[0]
                if len(legal_indices) > 0:
                    chosen_action = int(legal_indices[np.argmax(policy_probs[legal_indices])])
                else:
                    chosen_action = 0

                observation, step_reward, is_terminated, is_truncated, _ = self.eval_environment.step(chosen_action)
                cumulative_reward += float(step_reward)
                turn_count += 1

            if cumulative_reward > 0:
                wins += 1
            rewards.append(cumulative_reward)
            turns.append(turn_count)

        win_rate = wins / max(1, n_episodes)
        mean_reward = float(np.mean(rewards)) if rewards else 0.0
        mean_turns = float(np.mean(turns)) if turns else 0.0
        return win_rate, mean_reward, mean_turns

    def learn(
        self,
        total_episodes: int = 1000,
        training_steps_per_episode: int = 8,
        checkpoint_frequency: int = 25,
        start_episode: int = 1,
    ) -> "ExpertIterationTrainer":
        """Runs the complete self-play and training loop (AlphaZero / Expert Iteration).

        This method serves as the training entrypoint, replacing standard on-policy
        PPO model.learn() with lookahead-guided policy distillation and value regression.
        """
        self.run_training_loop(
            total_episodes=total_episodes,
            training_steps_per_episode=training_steps_per_episode,
            checkpoint_frequency=checkpoint_frequency,
            start_episode=start_episode,
        )
        return self

    def run_training_loop(
        self,
        total_episodes: int = 1000,
        training_steps_per_episode: int = 8,
        checkpoint_frequency: int = 25,
        start_episode: int = 1,
    ) -> None:
        """Runs the complete self-play and training loop."""
        print(f"Starting Expert Iteration Training from Episode {start_episode} to {total_episodes} on device: {self.device}")
        print(f"Lookahead Engine: 2-Turn Nash Equilibrium (Simultaneous Matrix Solver)")
        recent_rewards: collections.deque[float] = collections.deque(maxlen=50)

        for episode_index in range(start_episode, total_episodes + 1):
            episode_reward, episode_length = self.collect_lookahead_episode()
            recent_rewards.append(episode_reward)

            # Train the network on accumulated lookahead search data
            total_loss, policy_loss, value_loss = 0.0, 0.0, 0.0
            for _ in range(training_steps_per_episode):
                step_total, step_pol, step_val = self.train_step()
                total_loss += step_total
                policy_loss += step_pol
                value_loss += step_val

            average_total_loss = total_loss / max(1, training_steps_per_episode)
            average_policy_loss = policy_loss / max(1, training_steps_per_episode)
            average_value_loss = value_loss / max(1, training_steps_per_episode)
            win_rate = sum(1 for reward in recent_rewards if reward > 0) / len(recent_rewards)

            if episode_index % 5 == 0 or episode_index == start_episode:
                print(
                    f"Episode {episode_index:4d}/{total_episodes} | "
                    f"Turns: {episode_length:2d} | "
                    f"Reward: {episode_reward:+.2f} | "
                    f"WinRate(last 50): {win_rate * 100:.1f}% | "
                    f"Buffer: {len(self.replay_buffer):5d} | "
                    f"PolicyLoss: {average_policy_loss:.4f} | "
                    f"ValueLoss: {average_value_loss:.4f}"
                )

            # Checkpoint saving & benchmark validation
            if episode_index % checkpoint_frequency == 0 or episode_index == total_episodes:
                checkpoint_path = os.path.join(
                    self.checkpoint_directory, f"expert_iteration_model_{episode_index}_episodes.zip"
                )
                self.model.save(checkpoint_path)
                print(f"Saved checkpoint to {checkpoint_path}")

                # Save as current best model
                best_model_path = os.path.join(self.best_model_directory, "best_model.zip")
                self.model.save(best_model_path)
                print(f"Updated best model at {best_model_path}")

                preview_checkpoint_path = os.path.join(
                    self.checkpoint_directory, f"team_preview_model_{episode_index}_episodes.pt"
                )
                torch.save(self.preview_model.state_dict(), preview_checkpoint_path)
                
                best_preview_path = os.path.join(self.best_model_directory, "best_team_preview_model.pt")
                torch.save(self.preview_model.state_dict(), best_preview_path)
                
                # Periodic Benchmark Evaluation against SimpleHeuristics baseline
                if self.eval_environment is not None:
                    eval_win_rate, eval_reward, eval_turns = self.evaluate_benchmark(n_episodes=5)
                    print(
                        f"\n>>> [Benchmark Eval @ Ep {episode_index}] vs SimpleHeuristics: "
                        f"Win Rate: {eval_win_rate * 100:.1f}% | Avg Turns: {eval_turns:.1f} | Avg Reward: {eval_reward:+.2f}\n"
                    )

def main():
    team_file_path = os.path.join(os.path.dirname(__file__), "..", "teams", "MC306.txt")
    with open(team_file_path, "r", encoding="utf-8") as file_handle:
        team_paste = file_handle.read().strip()

    training_opponent = LookaheadPlayer(
        battle_format="gen9championsvgc2026regmc",
        team=team_paste,
        depth=2,
        max_candidates=6,
    )
    raw_environment = VGCEnv(opponent=training_opponent)
    raw_environment.agent.update_team(team=team_paste)
    monitored_environment = Monitor(raw_environment)

    eval_opponent = SimpleHeuristicsPlayer(
        battle_format="gen9championsvgc2026regmc",
        team=team_paste,
        accept_open_team_sheet=True,
        account_configuration=AccountConfiguration(f"Heuristic_{uuid.uuid4().hex[:6]}", None),
    )
    eval_environment = VGCEnv(opponent=eval_opponent)
    eval_environment.agent.update_team(team=team_paste)

    best_checkpoint_path = "./checkpoints/best_model/best_model.zip"
    best_preview_checkpoint_path = "./checkpoints/best_model/best_team_preview_model.pt"

    device_name = "cuda" if (torch and torch.cuda.is_available()) else "cpu"
    start_episode = 1

    checkpoint_dir = "./checkpoints/expert_iteration/"
    if os.path.exists(checkpoint_dir):
        for filename in os.listdir(checkpoint_dir):
            file_path = os.path.join(checkpoint_dir, filename)
            if os.path.isfile(file_path):
                os.remove(file_path)

    if os.path.exists(best_checkpoint_path):
        print(f"Loading existing model from {best_checkpoint_path}...")
        ppo_model = MaskablePPO.load(best_checkpoint_path, env=monitored_environment, device=device_name)
    else:
        print("Initializing fresh MaskablePPO model...")
        policy_arguments = dict(
            features_extractor_class=VGCFeatureExtractor,
            features_extractor_kwargs=dict(ability_dim=32, item_dim=32),
            net_arch=dict(pi=[512, 256], vf=[512, 256]),
        )
        ppo_model = MaskablePPO(
            MaskableMultiInputActorCriticPolicy,
            monitored_environment,
            policy_kwargs=policy_arguments,
            device=device_name,
            tensorboard_log="./logs/",
            verbose=1,
        )
        
    if os.path.exists(best_preview_checkpoint_path):
        print(f"Loading existing team preview model from {best_preview_checkpoint_path}...")
        preview_model = TeamPreviewModel(ability_dim=32, item_dim=32).to(device_name)
        preview_model.load_state_dict(torch.load(best_preview_checkpoint_path, map_location=device_name))
    else:
        print("Initializing fresh TeamPreviewModel...")
        preview_model = TeamPreviewModel(ability_dim=32, item_dim=32).to(device_name)

    trainer = ExpertIterationTrainer(
        model=ppo_model,
        training_environment=raw_environment,
        preview_model=preview_model,
        eval_environment=eval_environment,
        search_depth=2,
        search_candidates_limit=10,
        replay_buffer_capacity=15000,
        learning_rate=1e-4,
        batch_size=64,
        policy_loss_weight=1.0,
        value_loss_weight=0.5,
        entropy_weight=0.01,
        checkpoint_directory="./checkpoints/expert_iteration/",
        best_model_directory="./checkpoints/best_model/",
        device=device_name,
    )

    # Ensure that the agent shares the same team preview model as the trainer so it can be updated during training
    # and used during evaluation
    raw_environment.agent.team_preview_model = trainer.preview_model
    eval_environment.agent.team_preview_model = trainer.preview_model

    trainer.learn(
        total_episodes=1000,
        training_steps_per_episode=8,
        checkpoint_frequency=25,
        start_episode=start_episode,
    )

if __name__ == "__main__":
    main()
